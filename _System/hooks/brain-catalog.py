#!/usr/bin/env python3
"""
Auto-generate per-folder catalogs for the brain vault.

Why: hand-maintained _index.md catalogs drift (2026-06-11 audit: Knowledge
index ~70% accurate — 7 ghost entries, 5 orphaned files; Sessions/Decisions/
Mistakes/Patterns had no catalog at all). Hand-curation of listings is a
losing game; generate them instead.

Output: {folder}/_catalog.md per runtime folder. These are .gitignore'd
automatically (Knowledge/** etc.), so device-specific listings never leak
into the shared skeleton. The tracked _index.md files keep only curated
prose + a pointer to _catalog.md.

Invoked: (a) spawned by distill-session.py after writing notes,
(b) spawned detached by brain-health.py at session start, (c) manually.
Fast: frontmatter scan only, no LLM, no embeddings.
"""
import os
import re
import sys
from datetime import datetime
from pathlib import Path

# Home-relative fallback (not a device-specific absolute path) — the installer's
# generated launcher and distill-session.py's own spawn always pass
# CLAUDE_DISTILL_VAULT explicitly; this fallback only matters for an ad-hoc
# invocation with no env var set.
BRAIN = Path(os.environ.get("CLAUDE_DISTILL_VAULT", str(Path.home() / "brain")))

# folder -> grouping style
FOLDERS = {
    "Knowledge": "flat",
    "Sessions": "by-month",
    "Decisions": "by-month",
    "Mistakes": "by-month",
    "Patterns": "by-month",
    "Memory": "flat",
    "Agents": "flat",
}

FM_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.DOTALL)
H1_RE = re.compile(r"^#\s+(.+)$", re.MULTILINE)
DATE_PREFIX_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})")


def read_meta(f: Path) -> dict:
    try:
        head = f.read_text(encoding="utf-8", errors="replace")[:4000]
    except OSError:
        return {}
    meta = {}
    m = FM_RE.match(head)
    if m:
        for line in m.group(1).splitlines():
            kv = re.match(r"^(\w[\w-]*):\s*(.+?)\s*$", line)
            if kv:
                meta[kv.group(1).lower()] = kv.group(2).strip("'\"")
        head = head[m.end():]
    h1 = H1_RE.search(head)
    if h1 and "title" not in meta:
        meta["title"] = h1.group(1).strip()
    return meta


def entry_line(f: Path, meta: dict) -> str:
    title = meta.get("title") or f.stem
    desc = meta.get("summary") or meta.get("description") or ""
    if desc and desc != title:
        desc = f" — {desc[:120]}"
    else:
        desc = ""
    return f"- [{title}]({f.name}){desc}"


def file_date(f: Path, meta: dict) -> str:
    for key in ("date", "updated", "created"):
        v = meta.get(key, "")
        if re.match(r"^\d{4}-\d{2}-\d{2}", v):
            return v[:10]
    m = DATE_PREFIX_RE.match(f.stem)
    if m:
        return m.group(1)
    return datetime.fromtimestamp(f.stat().st_mtime).strftime("%Y-%m-%d")


def build_catalog(folder: Path, style: str) -> str:
    files = [f for f in sorted(folder.glob("*.md"))
             if f.name not in ("_index.md", "_catalog.md")]
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "---",
        f"title: {folder.name} catalog (auto-generated)",
        "type: catalog",
        f"generated: {now}",
        "---",
        "",
        f"# {folder.name} — device catalog",
        "",
        f"> Auto-generated by brain-catalog.py — **do not hand-edit** "
        f"(regenerated on distill / session start). {len(files)} files.",
        "",
    ]
    metas = {f: read_meta(f) for f in files}
    if style == "by-month":
        dated = sorted(files, key=lambda f: file_date(f, metas[f]), reverse=True)
        cur_month = None
        for f in dated:
            d = file_date(f, metas[f])
            month = d[:7]
            if month != cur_month:
                lines.append(f"\n## {month}\n")
                cur_month = month
            lines.append(f"- {d[5:]} {entry_line(f, metas[f])[2:]}")
    else:
        for f in files:
            d = file_date(f, metas[f])
            lines.append(f"{entry_line(f, metas[f])} ({d})")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    if not BRAIN.is_dir():
        print(f"brain vault missing: {BRAIN}")
        return 1
    written = 0
    for name, style in FOLDERS.items():
        folder = BRAIN / name
        if not folder.is_dir():
            continue
        out = folder / "_catalog.md"
        content = build_catalog(folder, style)
        old = out.read_text(encoding="utf-8") if out.exists() else ""
        # avoid mtime churn when nothing changed (ignore the generated: line)
        strip = lambda s: re.sub(r"^generated:.*$", "", s, flags=re.MULTILINE)
        if strip(old) != strip(content):
            out.write_text(content, encoding="utf-8")
            written += 1
    print(f"brain-catalog: {written} catalog(s) regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
